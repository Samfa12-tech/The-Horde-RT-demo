"""Add the Church fork's ordinary silver cache to the admitted town.

Blender --background --factory-startup --python-exit-code 1 --python
  tools/author-bellwether-road-cache.py -- ROOT PREVIOUS_TOWN_GLB NEW_OUTPUT
"""
import json
from pathlib import Path
import runpy
import sys

import bpy


HERE = Path(__file__).resolve()
WORKS = HERE.with_name("author-bellwether-mill-works.py")
CROSSING = HERE.with_name("author-bellwether-mill-crossing.py")
work = runpy.run_path(str(WORKS))
crossing = runpy.run_path(str(CROSSING))
TOWN = Path("assets/models/world/runtime/bellwether-tavern-v1")
PREVIOUS_TOWN = "bcd753a6286b57997a87e1f36ce21af5c6b7704949812a066c83b0ae3dace368"
BOX = (35.3, 82.95)
APPROACH = (33.6, 82.92)


def build_box(ground):
    wood = work["material"]("HordeTavernTimber", (.25, .12, .068), .87)
    iron = work["material"]("HordeHearthChar", (.06, .047, .041), .72)
    parts = []
    x, z = BOX
    floor = ground(x, z)

    def board(name, x0, x1, z0, z1, low, high, finish):
        parts.append(work["block"](name, x + x0, x + x1, z + z0, z + z1,
                                   floor + low, floor + high, finish))

    for foot in (-.32, .32):
        low = min(ground(x + foot, z - .20), ground(x + foot, z + .20)) - floor - .04
        board(f"Buried skid {foot}", foot-.06, foot+.06, -.23, .23, low, .14, wood)
    board("Box floor", -.38, .38, -.24, .24, .10, .17, wood)
    for end in (-.375, .30):
        board(f"End board {end}", end, end+.075, -.253, .253, .16, .50, wood)
    for side in (-.25, .184):
        for low in (.16, .34):
            board(f"Side stave {side} {low}", -.307, .307, side, side+.067, low, low+.162, wood)
    board("Broken lid end", .08, .398, -.255, .255, .477, .561, wood)
    board("Split lid remnant", -.185, .11, -.224, -.098, .477, .538, wood)
    for x0 in (-.337, .318):
        board(f"Forged exterior strap {x0}", x0-.017, x0+.017, .242, .259, .189, .501, iron)
    board("Old latch plate", -.383, -.369, -.07, .074, .324, .477, iron)
    return parts, (x, floor+.64, z)


def main(root, previous, output):
    terrain = root / work["TERRAIN"]
    if output.exists() or work["sha"](previous) != PREVIOUS_TOWN or work["sha"](terrain) != work["TERRAIN_HASH"]:
        raise ValueError("Choose a new output with the exact S6 town and admitted terrain.")
    bpy.ops.wm.read_factory_settings(use_empty=True)
    ground = work["terrain_probe"](terrain)
    bpy.data.orphans_purge(do_recursive=True)
    parts, reach = build_box(ground)
    output.mkdir(parents=True)
    master = output / "bellwether-road-cache.blend"
    bpy.ops.wm.save_as_mainfile(filepath=str(master), compress=True)
    crossing["join_parts"](parts, "BellwetherRoadCache")
    patch = output / "road-cache.glb"
    bpy.ops.export_scene.gltf(filepath=str(patch), export_format="GLB", use_selection=True,
                             export_apply=True, export_normals=True, export_tangents=True, export_animations=False)
    town = output / "bellwether-tavern-v1.glb"
    added, vertices, primitives = work["join_town"](previous, patch, town)
    original, _ = work["read_glb"](previous)
    indices = sum(original["accessors"][p["indices"]]["count"]
                  for mesh in original["meshes"] for p in mesh["primitives"]) + 3*added
    if not 0 < added <= 192 or primitives != 5 or vertices > 16000:
        raise ValueError(f"Road cache exceeds town budget: {added} new triangles, {vertices} vertices")
    manifest = json.loads((root / TOWN / "asset.manifest.json").read_bytes())
    manifest["budgets"].update(maxVertices=vertices, maxIndices=indices)
    manifest["lods"][0]["maxTriangles"] = indices//3
    work["save_json"](output / "asset.manifest.json", manifest)

    def mark(name, position):
        values = ", ".join(f"{value:.6f}f" for value in position)
        return f"inline constexpr std::array<float, {len(position)}> kRoadSilverCache{name}{{{{{values}}}}};"

    stage = ["#pragma once", "#include <array>", "#include <cstddef>", "",
             "// Generated by tools/author-bellwether-road-cache.py.",
             "namespace horde::gameplay::bellwether {",
             f"inline constexpr std::size_t kRoadSilverCacheSolidTriangles={added};",
             mark("Approach", APPROACH), mark("Reach", reach),
             "} // namespace horde::gameplay::bellwether", ""]
    (output / "geometry.generated.h").write_text("\n".join(stage), encoding="utf-8", newline="\n")
    work["save_json"](output / "authoring-receipt.json", dict(
        originalTownSha256=PREVIOUS_TOWN, terrainSha256=work["TERRAIN_HASH"], runtimeTownSha256=work["sha"](town),
        townVertices=vertices, townTriangles=indices//3, addedSolidTriangles=added, approach=APPROACH, reach=reach,
        recipeSha256=work["sha"](HERE), blender=bpy.app.version_string,
        files={name: work["sha"](output / name) for name in (
            master.name, patch.name, "asset.manifest.json", "geometry.generated.h", town.name)}))


if __name__ == "__main__":
    arguments = sys.argv[sys.argv.index("--") + 1:]
    if len(arguments) != 3:
        raise ValueError("Expected repository ROOT, PREVIOUS_TOWN_GLB and NEW_OUTPUT.")
    main(*(Path(argument).resolve() for argument in arguments))
