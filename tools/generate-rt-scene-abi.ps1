function Normalize-Newlines([string]$text) {
    return $text.Replace("`r`n", "`n").TrimEnd("`r", "`n") + "`n"
}

function Publish-OrCheck([string]$path, [string]$content) {
    $normalized = Normalize-Newlines $content
    if ($Check) {
        if (-not (Test-Path -LiteralPath $path)) {
            throw "RT scene ABI generated output is missing: $path"
        }
        $existing = Normalize-Newlines (Get-Content -LiteralPath $path -Raw)
        if ($existing -cne $normalized) {
            throw "RT scene ABI generated output is stale: $path"
        }
        return
    }
    $directory = Split-Path -Parent $path
    New-Item -ItemType Directory -Path $directory -Force | Out-Null
    [System.IO.File]::WriteAllText($path, $normalized, [System.Text.UTF8Encoding]::new($false))
}

Publish-OrCheck $CpuOutputPath $cpu
Publish-OrCheck $GlslOutputPath $glsl
if ($Check) {
    Write-Output "RT scene ABI generated outputs are current ($hash)."
} else {
    Write-Output "Generated RT scene ABI CPU/GLSL outputs ($hash)."
}
