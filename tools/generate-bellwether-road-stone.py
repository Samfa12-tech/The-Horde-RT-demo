"""Generate the native fixed-step transform track from the Blender receipt."""

import argparse
import json
from pathlib import Path


root = Path(__file__).resolve().parents[1]
source = root / "assets/models/world/source/bellwether-loose-road-stone-v1/road-contact.json"
output = root / "src/gameplay/dialogue/BellwetherRoadStone.generated.h"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
receipt = json.loads(source.read_text(encoding="utf-8"))
poses = receipt["poses"]
assert receipt["fps"] == 60 and receipt["contactFrame"] == 9
assert [pose["frame"] for pose in poses] == list(range(1, len(poses) + 1))
settled = receipt["settledFrame"]


def transform(pose):
    basis = pose["engineBasisColumns"]
    position = pose["worldPosition"]
    return [value for i in range(3) for value in (*[column[i] for column in basis], position[i])]


assert all(transform(pose) == transform(poses[settled - 1]) for pose in poses[settled - 1:])
rows = ["    {{" + ", ".join(f"{v:.7f}f" for v in transform(pose)) + "}}," for pose in poses[:settled]]
text = "\n".join([
    "#pragma once",
    "// Generated by tools/generate-bellwether-road-stone.py from road-contact.json.",
    "#include <array>",
    "namespace horde::gameplay::dialogue {",
    f"inline constexpr std::array<std::array<float, 12>, {settled}> kBellwetherRoadStoneTrack{{{{",
    *rows,
    "}};",
    "}",
    "",
])
if args.check:
    if not output.exists() or output.read_text(encoding="utf-8") != text:
        raise SystemExit(f"Stale generated track: {output}")
else:
    output.write_text(text, encoding="utf-8", newline="\n")
