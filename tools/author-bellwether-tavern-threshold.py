"""Widen Bellwether's south tavern doorway at its existing surveyed ramp."""
from pathlib import Path
import runpy
import sys

import numpy as np


RECIPE = Path(__file__).resolve()
town = runpy.run_path(str(RECIPE.with_name("author-bellwether-mill-works.py")))
SHELL = "bellwether-tavern-v1.glb"
LEAF = "bellwether-south-door.glb"
PARENT_PINS = {
    SHELL: "518ae34348dd2d8deba2ceaf3d34ad72bfd535b2a4bff329d9b5e27edf133783",
    LEAF: "65e78893ef1a5cf5ebd572ffa1dc67507526948fa3fce7a73796b2eaac239fb9",
}
ADDED_WIDTH = .24
LEAF_WIDTH = 2.02


def positions(doc, blocks, node_name, material_name):
    node, = (entry for entry in doc["nodes"] if entry["name"] == node_name)
    primitive, = (entry for entry in doc["meshes"][node["mesh"]]["primitives"]
                  if doc["materials"][entry["material"]]["name"] == material_name)
    accessor = primitive["attributes"]["POSITION"]
    return accessor, town["read_accessor"](doc, blocks, accessor).copy()


def widen_frame(parent, output):
    doc, blocks = town["read_glb"](parent)
    # Move the opening side of the masonry pier and lintel. Move the east
    # timber jamb and the matching end of the head trim by the same amount.
    # Every affected surface stays in its original plane or moves parallel.
    for material, x_faces, expected_count in (
        ("HordeTownStone", (83.4,), 24),
        ("HordeTavernTimber", (83.332, 83.4), 36),
    ):
        accessor, xyz = positions(doc, blocks, "BellwetherSolid", material)
        planes = np.isclose(xyz[:, 0, None], x_faces, rtol=0, atol=.0001).any(axis=1)
        faces = planes & (xyz[:, 2] > 118.76) & (xyz[:, 2] < 119.201)
        if np.count_nonzero(faces) != expected_count:
            raise ValueError(f"The pinned south frame vertex selection changed for {material}.")
        xyz[faces, 0] += ADDED_WIDTH
        town["write_accessor"](doc, blocks, accessor, xyz)
    town["save_glb"](output, doc, blocks)


def widen_leaf(parent, output):
    doc, blocks = town["read_glb"](parent)
    accessor, wood = positions(doc, blocks, "BellwetherSouthDoor", "HordeTavernTimber")
    if len(wood) != 240 or not np.isclose(wood[:, 0].max(), 2.0182, rtol=0, atol=.0001):
        raise ValueError("The pinned eight planks and rails changed.")
    wood[:, 0] *= (LEAF_WIDTH + ADDED_WIDTH) / LEAF_WIDTH
    town["write_accessor"](doc, blocks, accessor, wood)

    accessor, iron = positions(doc, blocks, "BellwetherSouthDoor", "HordeHearthChar")
    latch = iron[:, 0] >= 1.74 - .0001
    if len(iron) != 288 or np.count_nonzero(latch) != 192:
        raise ValueError("The pinned hinge and latch fittings changed.")
    iron[latch, 0] += ADDED_WIDTH
    town["write_accessor"](doc, blocks, accessor, iron)
    town["save_glb"](output, doc, blocks)


def main(parent, output):
    if output.exists() or any(town["sha"](parent / leaf) != pin for leaf, pin in PARENT_PINS.items()):
        raise ValueError("Use the two pinned GLBs and a fresh output directory.")
    output.mkdir(parents=True)
    widen_frame(parent / SHELL, output / SHELL)
    widen_leaf(parent / LEAF, output / LEAF)

    header = output / "geometry.generated.h"
    header.write_text("#pragma once\n\n// Generated by tools/author-bellwether-tavern-threshold.py.\n"
                      "namespace horde::gameplay::bellwether {\n"
                      f"inline constexpr float kSouthDoorAddedWidth={ADDED_WIDTH:.3f}f;\n"
                      "}\n", encoding="utf-8", newline="\n")
    town["save_json"](output / "authoring-receipt.json", {
        "inputSha256": PARENT_PINS,
        "recipeSha256": town["sha"](RECIPE),
        "addedWidthMetres": ADDED_WIDTH,
        "clearDoorWidthMetres": round(2.064 + ADDED_WIDTH, 3),
        "files": {name: town["sha"](output / name) for name in (SHELL, LEAF, header.name)},
    })


if __name__ == "__main__":
    main(*(Path(arg).resolve() for arg in sys.argv[sys.argv.index("--") + 1:]))
