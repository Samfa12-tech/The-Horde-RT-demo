"""Fit an original work lamp to the north end of Bellwether's admitted mill bench."""

import json
import math
from pathlib import Path
import runpy
import sys

import bpy


RECIPE = Path(__file__).resolve()
world = runpy.run_path(str(RECIPE.with_name("author-bellwether-mill-works.py")))
model = runpy.run_path(str(RECIPE.with_name("author-bellwether-mill-crossing.py")))
TOWN = Path("assets/models/world/runtime/bellwether-tavern-v1")
PARENT = "070b29b105fe591156d7f98c4f6fdbe449c24466bf8c91f99bee21fa91da7b5c"
BENCH_CORNER = (116.869, 115.018)


def build_lamp(ground):
    top = ground(116.73, 115.74) + .98
    x, z = BENCH_CORNER
    iron = world["material"]("HordeHearthChar", (.073, .055, .04), .8)
    clay = world["material"]("HordeTownRoofClay", (.26, .12, .065), .85)
    parts = []

    def box(label, x0, x1, z0, z1, y0, y1):
        parts.append(world["block"](label, x + x0, x + x1, z + z0, z + z1,
                                    top + y0, top + y1, iron))

    def turned(label, axis, profile, material):
        sides = 12
        ax, az = axis
        points = [(x + ax + r * math.cos(i * math.tau / sides), top + h,
                   z + az + r * math.sin(i * math.tau / sides))
                  for h, r in profile for i in range(sides)]
        strips = [tuple(row * sides + index for row, index in
                        ((level, i), (level + 1, i), (level + 1, (i + 1) % sides),
                         (level, (i + 1) % sides)))
                  for level in range(len(profile) - 1) for i in range(sides)]
        top_cap = tuple(reversed(range(len(points) - sides, len(points))))
        parts.append(model["mesh"](label, points, [tuple(range(sides)), *strips, top_cap], material))

    # A bolted foot and bent iron back carry the oil cup above the bearing.
    # The cup faces the working side. Its low rim leaves the flame exposed.
    box("Bench edge clamp", -.081, .085, -.077, .065, -.012, .052)
    box("Wrought upright", .035, .074, -.048, -.006, .042, .988)
    box("Cup support", .005, .114, -.034, .240, .733, .775)
    box("Rain hood support", .021, .106, -.039, .159, .969, 1.009)
    bowl = (.047, .203)
    turned("Oil cup with turned rim", bowl,
           ((.767, .059), (.796, .112), (.839, .131), (.855, .124), (.855, .102), (.801, .083)), clay)
    turned("Charred wick", bowl, ((.801, .017), (.863, .011)), iron)
    turned("Iron rain hood", bowl,
           ((.996, .139), (1.021, .143), (1.060, .094), (1.071, .093), (1.064, .068), (1.023, .062)), iron)
    flame = (x + bowl[0], top + .859, z + bowl[1])
    light = (flame[0] - .077, flame[1] + .091, flame[2] + .028)
    return parts, (x, top, z), flame, light


def main(root, previous, output):
    terrain = root / world["TERRAIN"]
    if output.exists() or world["sha"](previous) != PARENT or world["sha"](terrain) != world["TERRAIN_HASH"]:
        raise ValueError("Expected the exact previous town and terrain and a new output directory.")
    bpy.ops.wm.read_factory_settings(use_empty=True)
    ground = world["terrain_probe"](terrain)
    bpy.data.orphans_purge(do_recursive=True)
    parts, shoe, flame, light = build_lamp(ground)
    output.mkdir(parents=True)
    master = output / "bellwether-mill-lamp.blend"
    bpy.ops.wm.save_as_mainfile(filepath=str(master), compress=True)
    model["join_parts"](parts, "BellwetherMillBenchLamp")
    patch = output / "mill-bench-lamp.glb"
    bpy.ops.export_scene.gltf(filepath=str(patch), export_format="GLB", use_selection=True,
                             export_apply=True, export_normals=True, export_tangents=True, export_animations=False)
    town = output / "bellwether-tavern-v1.glb"
    added, vertices, primitives = world["join_town"](previous, patch, town)
    if not 0 < added <= 420 or primitives != 5 or vertices > 58000:
        raise ValueError(f"Lamp exceeds town budget: {added} triangles, {vertices} combined vertices")
    parent, _ = world["read_glb"](previous)
    indices = sum(parent["accessors"][p["indices"]]["count"] for mesh in parent["meshes"]
                  for p in mesh["primitives"]) + 3 * added
    manifest = json.loads((root / TOWN / "asset.manifest.json").read_bytes())
    manifest["budgets"].update(maxVertices=vertices, maxIndices=indices)
    manifest["lods"][0]["maxTriangles"] = indices // 3
    world["save_json"](output / "asset.manifest.json", manifest)
    header = ["#pragma once", "#include <array>", "#include <cstddef>", "",
              "// Generated by tools/author-bellwether-mill-lamp.py.", "namespace horde::gameplay::bellwether {",
              f"inline constexpr std::size_t kMillBenchLampSolidTriangles={added};"]
    for name, xyz in (("Foot", shoe), ("Flame", flame), ("Light", light)):
        values = ", ".join(f"{value:.7f}f" for value in xyz)
        header.append(f"inline constexpr std::array<float,3> kMillBenchLamp{name}{{{{{values}}}}};")
    header += ["} // namespace horde::gameplay::bellwether", ""]
    layout = output / "geometry.generated.h"
    layout.write_text("\n".join(header), encoding="utf-8", newline="\n")
    files = master, patch, town, output / "asset.manifest.json", layout
    world["save_json"](output / "authoring-receipt.json", dict(
        feature="B05 mill bench oil lamp", originalTownSha256=PARENT, terrainSha256=world["TERRAIN_HASH"],
        runtimeTownSha256=world["sha"](town), lampFoot=shoe, lampFlame=flame, lampLight=light,
        addedSolidTriangles=added, townVertices=vertices, townTriangles=indices // 3,
        blender=bpy.app.version_string, recipeSha256=world["sha"](RECIPE),
        files={item.name: world["sha"](item) for item in files}))


if __name__ == "__main__":
    args = sys.argv[sys.argv.index("--") + 1:]
    if len(args) != 3:
        raise ValueError("Expected ROOT, PREVIOUS_TOWN_GLB and NEW_OUTPUT.")
    main(*(Path(arg).resolve() for arg in args))
