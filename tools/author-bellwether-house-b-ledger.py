"""Set a local stock ledger beside the oil cup in Bellwether's House B.

Run with Blender: -- ROOT PARENT_TOWN_GLB NEW_OUTPUT. Keep the parent manifest
beside its GLB. The runtime export reuses the town's existing material rows.
"""

import json
from pathlib import Path
import runpy
import sys

import bpy


RECIPE = Path(__file__).resolve()
TOWN = runpy.run_path(str(RECIPE.with_name("author-bellwether-mill-works.py")))
MESHES = runpy.run_path(str(RECIPE.with_name("author-bellwether-mill-crossing.py")))
PARENT = "0ed222271e8eeab9345386ee985a7a446c85eb7399efa9500df7f6f3a0902e01"


def make_ledger(x, y, z):
    leather = TOWN["material"]("HordeTownRoofClay", (.27, .13, .075), .87)
    paper = TOWN["material"]("HordeTownStone", (.35, .30, .22), .92)
    ink = TOWN["material"]("HordeHearthChar", (.06, .05, .04), .81)
    block = TOWN["block"]
    cover = block("Worn clay-coloured binding", x-.32, x+.32, z-.181, z+.181, y, y+.018, leather, .007)
    parts = [cover]
    for side in (-1, 1):
        left, right = sorted((x + side*.008, x + side*.30))
        parts.append(block("Layered paper edges", left, right, z-.162, z+.162, y+.017, y+.039, paper, .005))
        # Two gently tilted halves lift at the sewn fold. The marks follow
        # the same surface and catch the nearby table lamp.
        points = [(x+side*.008, y+.063, z-.162), (x+side*.30, y+.041, z-.162),
                  (x+side*.30, y+.041, z+.162), (x+side*.008, y+.063, z+.162)]
        face = (0, 3, 2, 1) if side > 0 else (0, 1, 2, 3)
        parts.append(MESHES["mesh"]("Open page", points, [face], paper))
        for row in range(5):
            mark_z = z - .102 + row*.043
            inner = .047 + row%2*.011
            outer = .246 - row%3*.029
            coords = [(x+side*p, y+.064-(p-.008)*.022/.292, mark_z+depth)
                      for p, depth in ((inner,0), (outer,0), (outer-.009,.007), (inner,.006))]
            parts.append(MESHES["mesh"]("Handwritten stock marks", coords, [face], ink))
    return parts


def main(root, parent, output):
    if output.exists() or TOWN["sha"](parent) != PARENT:
        raise ValueError("Expected the pinned previous town and an unused output directory")
    house = root / "assets/models/world/source/bellwether-house-b-v1/geometry.generated.h"
    import re
    floor = float(re.search(r"kHouseBFloorY=(-?[0-9.]+)f", house.read_text()).group(1))
    x, y, z = 35.43, floor + .96, 99.83
    bpy.ops.wm.read_factory_settings(use_empty=True)
    parts = make_ledger(x, y, z)
    output.mkdir(parents=True)
    master = output / "house-b-stock-ledger.blend"
    bpy.ops.wm.save_as_mainfile(filepath=str(master), compress=True)
    MESHES["join_parts"](parts, "HouseBStockLedger")
    patch = output / "house-b-stock-ledger.glb"
    bpy.ops.export_scene.gltf(filepath=str(patch), export_format="GLB", use_selection=True,
                             export_apply=True, export_normals=True, export_tangents=True, export_animations=False)
    runtime = output / "bellwether-tavern-v1.glb"
    added, vertices, primitives = TOWN["join_town"](parent, patch, runtime)
    if not 0 < added <= 200 or primitives != 6:
        raise ValueError(f"Unexpected ledger budget: {added} solid triangles, {primitives} primitives")
    glb, _ = TOWN["read_glb"](runtime)
    indices = sum(glb["accessors"][part["indices"]]["count"] for mesh in glb["meshes"] for part in mesh["primitives"])
    manifest = json.loads(parent.with_name("asset.manifest.json").read_bytes())
    manifest["budgets"].update(maxVertices=vertices, maxIndices=indices)
    manifest["lods"][0]["maxTriangles"] = indices // 3
    manifest_path = output / "asset.manifest.json"
    TOWN["save_json"](manifest_path, manifest)
    header = output / "geometry.generated.h"
    header.write_text(
        "#pragma once\n#include <array>\n#include <cstddef>\n\n"
        "// Generated by tools/author-bellwether-house-b-ledger.py.\n"
        "namespace horde::gameplay::bellwether {\n"
        f"inline constexpr std::size_t kHouseBLedgerSolidTriangles={added};\n"
        f"inline constexpr std::array<float,3> kHouseBLedgerPosition{{{{{x:.7f}f, {y+.06:.7f}f, {z:.7f}f}}}};\n"
        "} // namespace horde::gameplay::bellwether\n", encoding="utf-8", newline="\n")
    TOWN["save_json"](output / "authoring-receipt.json", dict(
        feature="B04 stock ledger at its occupied sorting table", originalTownSha256=PARENT,
        houseLayoutSha256=TOWN["sha"](house), addedSolidTriangles=added, primitives=primitives,
        position=[x, y+.06, z], blender=bpy.app.version_string, recipeSha256=TOWN["sha"](RECIPE),
        files={file.name: TOWN["sha"](file) for file in (master, patch, runtime, manifest_path, header)}))


if __name__ == "__main__":
    args = sys.argv[sys.argv.index("--")+1:]
    if len(args) != 3:
        raise ValueError("Expected ROOT, PARENT_TOWN_GLB and NEW_OUTPUT")
    main(*(Path(arg).resolve() for arg in args))
