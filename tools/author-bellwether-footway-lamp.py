"""Author a hooded oil lamp at the stone turn toward the Bellwether wheel."""
import json
from pathlib import Path
import runpy
import sys

import bpy


RECIPE = Path(__file__).resolve()
town = runpy.run_path(str(RECIPE.with_name("author-bellwether-mill-works.py")))
crossing = runpy.run_path(str(RECIPE.with_name("author-bellwether-mill-crossing.py")))
TOWN_NAME = "bellwether-tavern-v1.glb"
PARENT_SHA256 = "8ab300d12555b3413b94a0d22c907bf4776413693e989f96a624ce7313c0f61a"
FOOT_X, FOOT_Z = 134.09, 121.31


def author(ground):
    foot = ground(FOOT_X, FOOT_Z)
    wood = town["material"]("HordeTavernTimber", (.25, .115, .065), .84)
    stone = town["material"]("HordeTownStone", (.22, .20, .16), 1.)
    iron = town["material"]("HordeHearthChar", (.073, .055, .04), .8)
    clay = town["material"]("HordeTownRoofClay", (.26, .12, .065), .85)

    def block(name, x0, x1, z0, z1, y0, y1, material, bevel):
        return town["block"](name, FOOT_X+x0, FOOT_X+x1, FOOT_Z+z0, FOOT_Z+z1,
                             foot+y0, foot+y1, material, bevel)

    parts = [
        block("Buried stone footing", -.13,.13,-.12,.12,-.16,.070,stone,.027),
        block("Oak lamp standard", -.068,.068,-.062,.062,.045,1.62,wood,.012),
        block("Wrought lamp arm", -.048,.265,-.025,.108,1.25,1.30,iron,.006),
        block("Turned clay oil cup", .116,.309,-.031,.169,1.29,1.372,clay,.025),
        block("Charred wick", .200,.225,.055,.080,1.366,1.400,iron,.005),
        block("Hood hanger", -.045,.285,-.033,.059,1.58,1.62,iron,.005),
    ]
    points = [(FOOT_X+x,foot+y,FOOT_Z+z) for x,y,z in (
        (.09,1.56,-.079),(.34,1.56,-.079),(.34,1.56,.218),(.09,1.56,.218),
        (.09,1.639,.050),(.34,1.639,.050),(.09,1.545,-.079),(.34,1.545,-.079),
        (.34,1.545,.218),(.09,1.545,.218))]
    parts.append(crossing["mesh"]("Folded iron rain hood", points,
        [(0,4,5,1),(4,3,2,5),(6,7,8,9),(0,1,7,6),(1,5,2,8,7),(2,3,9,8),(3,4,0,6,9)],iron))
    flame = (FOOT_X+.212, foot+1.403, FOOT_Z+.068)
    light = (flame[0]+.031, flame[1]+.085, flame[2]+.174)
    return parts, flame, light


def main(root, parent, output):
    previous = parent/TOWN_NAME
    terrain = root/town["TERRAIN"]
    if output.exists() or town["sha"](previous) != PARENT_SHA256 or town["sha"](terrain) != town["TERRAIN_HASH"]:
        raise ValueError("Use the pinned footway town, surveyed terrain and a fresh directory.")
    bpy.ops.wm.read_factory_settings(use_empty=True)
    ground = town["terrain_probe"](terrain)
    bpy.data.orphans_purge(do_recursive=True)
    parts, flame, light = author(ground)
    output.mkdir(parents=True)
    master, patch, runtime = (output/name for name in ("footway-lamp.blend", "lamp.glb", TOWN_NAME))
    bpy.ops.wm.save_as_mainfile(filepath=str(master), compress=True)
    crossing["join_parts"](parts, "BellwetherFootwayLamp")
    bpy.ops.export_scene.gltf(filepath=str(patch), export_format="GLB", use_selection=True,
                             export_apply=True, export_normals=True, export_tangents=True,
                             export_animations=False)
    count, vertices, primitives = town["join_town"](previous, patch, runtime)
    if not 0 < count <= 340 or primitives != 6:
        raise ValueError("Footway lamp exceeds its town geometry budget.")
    manifest = json.loads((parent/"asset.manifest.json").read_bytes())
    manifest["budgets"]["maxVertices"] = vertices
    manifest["budgets"]["maxIndices"] += count*3
    manifest["lods"][0]["maxTriangles"] += count
    town["save_json"](output/"asset.manifest.json", manifest)
    header = output/"geometry.generated.h"
    lines = ["#pragma once", "#include <array>", "#include <cstddef>", "",
             "// Generated by tools/author-bellwether-footway-lamp.py.", "namespace horde::gameplay::bellwether {",
             f"inline constexpr std::size_t kFootwayLampSolidTriangles={count};"]
    for name, xyz in (("Flame", flame), ("Light", light)):
        values = ", ".join(f"{v:.7f}f" for v in xyz)
        lines.append(f"inline constexpr std::array<float,3> kFootwayLamp{name}{{{{{values}}}}};")
    header.write_text("\n".join([*lines, "}", ""]), encoding="utf-8", newline="\n")
    town["save_json"](output/"authoring-receipt.json", dict(parentTownSha256=PARENT_SHA256,
        parentTerrainSha256=town["sha"](terrain), recipeSha256=town["sha"](RECIPE), blender=bpy.app.version_string,
        addedSolidTriangles=count, flame=flame, light=light,
        files={f.name:town["sha"](f) for f in (master, runtime, header, output/"asset.manifest.json")}))


if __name__ == "__main__":
    main(*(Path(arg).resolve() for arg in sys.argv[sys.argv.index("--")+1:]))
